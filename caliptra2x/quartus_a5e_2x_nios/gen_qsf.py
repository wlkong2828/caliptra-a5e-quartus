#!/usr/bin/env python3
"""Generate nios_caliptra2x_a5e.qsf: Nios V + Caliptra 2.x full system (top nios_caliptra2x_top).
Caliptra 2.x sources, search paths and macros are taken from ../quartus_a5e_2x/caliptra2x_a5e.qsf
(the core-only study QSF, itself generated by its gen_qsf.py) and rebased to this directory; device,
pins and Nios/IP/glue settings mirror ../../quartus_a5e_nios/nios_caliptra_a5e.qsf (Caliptra 1.1)."""
import os, re
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "quartus_a5e_2x", "caliptra2x_a5e.qsf")
SRC_DIR = os.path.dirname(SRC)
def rebase(p):
    a = os.path.normpath(os.path.join(SRC_DIR, p))
    assert os.path.exists(a), a
    return os.path.relpath(a, HERE)
inc, files = [], []
for l in open(SRC):
    m = re.match(r"set_global_assignment -name (SEARCH_PATH|SYSTEMVERILOG_FILE) (\S+)", l.strip())
    if not m: continue
    (inc if m.group(1) == "SEARCH_PATH" else files).append(rebase(m.group(2)))
par = os.environ.get("QPAR", "4")
o = [
 '# AUTO-GENERATED by gen_qsf.py - Nios V/m host + Caliptra 2.x (caliptra-rtl v2.1.2 49370266) passive, full system.',
 '# Paths are relative to this directory. Upstream RTL: ../../external/caliptra-rtl-2x (git submodule):',
 '# run ../../scripts/fetch_deps.sh first. Same device / pins / Nios system as ../../quartus_a5e_nios (Caliptra 1.1).',
 'set_global_assignment -name FAMILY "Agilex 5"',
 'set_global_assignment -name DEVICE A5EC065BB32AE6S',
 'set_global_assignment -name TOP_LEVEL_ENTITY nios_caliptra2x_top',
 'set_global_assignment -name VERILOG_INPUT_VERSION SYSTEMVERILOG_2005',
 'set_global_assignment -name VERILOG_CU_MODE MFCU',
 'set_global_assignment -name PROJECT_OUTPUT_DIRECTORY output_files',
 'set_global_assignment -name VERILOG_CONSTANT_LOOP_LIMIT 131072',
 'set_global_assignment -name VERILOG_MACRO "SYNTHESIS=1"',
 'set_global_assignment -name VERILOG_MACRO "FPGA_SYN=1"',
 f'set_global_assignment -name NUM_PARALLEL_PROCESSORS {par}',
 '# Same as the 1.x Nios project: all top I/O virtual except clk and reset_n (board pins: guide section 17)',
 'set_instance_assignment -name VIRTUAL_PIN ON -to *',
 'set_instance_assignment -name VIRTUAL_PIN OFF -to clk',
 'set_instance_assignment -name VIRTUAL_PIN OFF -to reset_n',
 'set_global_assignment -name SDC_FILE nios_caliptra2x.sdc',
]
o += [f'set_global_assignment -name SEARCH_PATH {d}' for d in inc]
o += [f'set_global_assignment -name SYSTEMVERILOG_FILE {f}' for f in files]
o += [
 '',
 '# ---- Nios V host system (qsys/nios_caliptra2x_sys.tcl; same IP set as 1.x nios_caliptra_sys) ----',
 'set_global_assignment -name QSYS_FILE qsys/nios_caliptra2x_sys.qsys',
] + [f'set_global_assignment -name IP_FILE qsys/ip/nios_caliptra2x_sys/nios_caliptra2x_sys_{n}.ip'
     for n in ("caliptra_win", "clk", "cpu", "ctrl_pio", "jtag_uart", "magic_pio", "ram", "status_pio")] + [
 '# ---- SoC glue (2.x ports of the 1.x quartus_a5e_nios/rtl blocks) + Reset Release IP ----',
 'set_global_assignment -name SYSTEMVERILOG_FILE ../rtl_2x/avmm_to_axi.sv',
 'set_global_assignment -name SYSTEMVERILOG_FILE ../rtl_2x/soc_fuse_ctrl2x.sv',
 'set_global_assignment -name SYSTEMVERILOG_FILE ../rtl_2x/soc_fw_store.sv',
 'set_global_assignment -name SYSTEMVERILOG_FILE ../rtl_2x/reset_sync.sv',
 'set_global_assignment -name IP_FILE ip/rst_release.ip',
 'set_global_assignment -name SYSTEMVERILOG_FILE ../rtl_2x/nios_caliptra2x_top.sv',
 'set_global_assignment -name HEX_FILE ../fw_2x/caliptra-rom.hex',
 'set_global_assignment -name HEX_FILE ../fw_2x/caliptra-fw-bundle.hex',
 'set_global_assignment -name HEX_FILE ../fw_2x/fuse_image_2x.hex',
 'set_global_assignment -name PWRMGT_VOLTAGE_OUTPUT_FORMAT "LINEAR FORMAT"',
 'set_global_assignment -name PWRMGT_LINEAR_FORMAT_N "-12"',
]
open(os.path.join(HERE, "nios_caliptra2x_a5e.qsf"), "w").write("\n".join(o) + "\n")
print(len(inc), "incdirs,", len(files) + 5, "SV files")
