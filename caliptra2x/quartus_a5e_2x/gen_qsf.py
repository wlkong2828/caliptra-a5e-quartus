#!/usr/bin/env python3
"""Generate caliptra2x_a5e.qsf (synthesis-only size study) from the Verilator file list
ref/agilex7-2x-phaseA/caliptra_passive_top.f (caliptra-rtl v2.1.2, absolute paths)."""
import os
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
FLIST = os.path.join(ROOT, "ref/agilex7-2x-phaseA/caliptra_passive_top.f")
RTL = "/workspace/caliptra-rtl"
OVR = {  # upstream file basename -> synthesis override
    "caliptra_sram.sv": f"{HERE}/syn_src/caliptra_sram.sv",
    "abr_1r1w_ram.sv": f"{HERE}/syn_src/abr_1r1w_ram.sv",
    "abr_1r1w_be_ram.sv": f"{HERE}/syn_src/abr_1r1w_be_ram.sv",
    "abr_1r1w_512x4_ram.sv": f"{HERE}/syn_src/abr_1r1w_512x4_ram.sv",
}
REMAP = {
    "/workspace/caliptra-agilex/patches/decompress_top.sv": f"{RTL}/submodules/adams-bridge/src/decompress/rtl/decompress_top.sv",
    "/workspace/caliptra-agilex/rtl/caliptra_veer_sram_export.sv": f"{ROOT}/rtl_2x/caliptra_veer_sram_export.sv",
    "/workspace/caliptra-agilex/rtl/caliptra_passive_top.sv": f"{ROOT}/rtl_2x/caliptra_passive_top.sv",
}
inc, files = [], []
for l in open(FLIST):
    l = l.strip()
    if not l or l.startswith("//"): continue
    if l.startswith("+incdir+"): inc.append(l[8:]); continue
    # .svh kept in list order: several files use macros (CALIPTRA_ASSERT, ABR_ICG, ABR_ASSERT) without `include (MFCU)
    l = REMAP.get(l, l); l = OVR.get(os.path.basename(l), l)
    if l not in files: files.append(l)
for f in files: assert os.path.exists(f), f
par = os.environ.get("QPAR", "4")
o = [
 '# AUTO-GENERATED by gen_qsf.py - Caliptra 2.x (v2.1.2 49370266) core-only passive top, synthesis-only size study',
 'set_global_assignment -name FAMILY "Agilex 5"',
 'set_global_assignment -name DEVICE A5EC065BB32AE6S',
 'set_global_assignment -name TOP_LEVEL_ENTITY caliptra_passive_top',
 'set_global_assignment -name VERILOG_INPUT_VERSION SYSTEMVERILOG_2005',
 'set_global_assignment -name VERILOG_CU_MODE MFCU',
 'set_global_assignment -name PROJECT_OUTPUT_DIRECTORY output_files',
 'set_global_assignment -name VERILOG_CONSTANT_LOOP_LIMIT 131072',
 'set_global_assignment -name VERILOG_MACRO "SYNTHESIS=1"',
 'set_global_assignment -name VERILOG_MACRO "FPGA_SYN=1"',
 f'set_global_assignment -name NUM_PARALLEL_PROCESSORS {par}',
 '# size study: all top I/O virtual except clk (I/O count must not limit)',
 'set_instance_assignment -name VIRTUAL_PIN ON -to *',
 'set_instance_assignment -name VIRTUAL_PIN OFF -to clk',
 'set_instance_assignment -name VIRTUAL_PIN OFF -to jtag_tck',
 f'set_parameter -name ROM_INIT_FILE "{ROOT}/fw_2x/caliptra-rom.hex"',
 'set_global_assignment -name SDC_FILE caliptra2x_a5e.sdc',
]
o += [f'set_global_assignment -name SEARCH_PATH {d}' for d in inc]
o += [f'set_global_assignment -name SYSTEMVERILOG_FILE {f}' for f in files]
open(os.path.join(HERE, "caliptra2x_a5e.qsf"), "w").write("\n".join(o) + "\n")
print(len(inc), "incdirs,", len(files), "files")
